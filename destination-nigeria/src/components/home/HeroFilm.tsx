"use client";

import { useCallback, useEffect, useRef, useState, useSyncExternalStore } from "react";
import type { HeroFilm as HeroFilmMedia } from "@/content/media";
import { ENTERED_EVENT, welcomePending } from "../Welcome";

/** `svg` is inlined for the first scene only; later scenes are fetched from `src` just before they play. */
export type HeroScene = { svg: string | null; src: string; caption: string; alt: string };

const SCENE_MS = 7000;
const REDUCE = "(prefers-reduced-motion: reduce)";

function subscribeReducedMotion(cb: () => void) {
  const mq = window.matchMedia(REDUCE);
  mq.addEventListener("change", cb);
  return () => mq.removeEventListener("change", cb);
}

/**
 * The hero "film". With licensed footage configured it plays a muted,
 * looping video; otherwise it sequences the illustrated scenes. Either way a
 * visible control pauses all movement, and reduced-motion visitors get a
 * still first frame.
 */
export function HeroFilm({ scenes, video, children }: { scenes: HeroScene[]; video: HeroFilmMedia | null; children: React.ReactNode }) {
  const root = useRef<HTMLElement>(null);
  const videoRef = useRef<HTMLVideoElement>(null);
  const [index, setIndex] = useState(0);
  // Reduced motion starts paused on the first frame; the visitor's own choice wins after that.
  const reduceMotion = useSyncExternalStore(subscribeReducedMotion, () => window.matchMedia(REDUCE).matches, () => false);
  const [userPaused, setUserPaused] = useState<boolean | null>(null);
  const paused = userPaused ?? reduceMotion;
  const [entered, setEntered] = useState(false);
  const [showTranscript, setShowTranscript] = useState(false);
  const [svgs, setSvgs] = useState<(string | null)[]>(() => scenes.map((s) => s.svg));

  // Fetch the current and next scene artwork (same-origin, generated by /plates).
  useEffect(() => {
    if (video) return;
    const wanted = [index, (index + 1) % scenes.length].filter((i) => !svgs[i]);
    if (wanted.length === 0) return;
    let cancelled = false;
    Promise.all(wanted.map((i) => fetch(scenes[i]!.src).then((r) => (r.ok ? r.text() : null)).catch(() => null))).then((texts) => {
      if (cancelled) return;
      setSvgs((prev) => {
        const next = [...prev];
        wanted.forEach((i, k) => {
          const t = texts[k];
          if (t && t.trimStart().startsWith("<svg")) next[i] = t;
        });
        return next;
      });
    });
    return () => {
      cancelled = true;
    };
  }, [index, scenes, svgs, video]);

  // Opening sequence starts once the visitor has entered (immediately on repeat visits).
  useEffect(() => {
    const onEnter = () => setEntered(true);
    window.addEventListener(ENTERED_EVENT, onEnter);
    // Repeat visitors (or no welcome on this page): start straight away, on the next frame
    // so the hidden starting state paints first and the entrance can animate.
    const raf = welcomePending() && document.querySelector("dialog.welcome") ? 0 : requestAnimationFrame(onEnter);
    return () => {
      window.removeEventListener(ENTERED_EVENT, onEnter);
      cancelAnimationFrame(raf);
    };
  }, []);


  // Advance scenes; also stop when the hero is off-screen or the tab is hidden.
  const [visible, setVisible] = useState(true);
  useEffect(() => {
    const el = root.current;
    if (!el || !("IntersectionObserver" in window)) return;
    const io = new IntersectionObserver(([e]) => setVisible(Boolean(e?.isIntersecting)), { threshold: 0.05 });
    io.observe(el);
    return () => io.disconnect();
  }, []);

  useEffect(() => {
    if (video || paused || !entered || !visible) return;
    const t = window.setTimeout(() => setIndex((i) => (i + 1) % scenes.length), SCENE_MS);
    return () => window.clearTimeout(t);
  }, [index, paused, entered, visible, scenes.length, video]);

  useEffect(() => {
    const v = videoRef.current;
    if (!v) return;
    if (paused || !visible) v.pause();
    else void v.play().catch(() => setUserPaused(true));
  }, [paused, visible]);

  const toggle = useCallback(() => setUserPaused(!paused), [paused]);
  const current = scenes[index]!;

  return (
    <section ref={root} className={`hero on-dark${paused ? " is-paused" : ""}${entered ? " is-entered" : ""}`} aria-label="Introduction">
      <div className="hero-film" aria-hidden="true">
        {video ? (
          <video ref={videoRef} className="hero-video" muted loop playsInline autoPlay={!paused} preload="metadata" poster={video.poster}>
            {video.sources.map((s) => (
              <source key={s.src} src={s.src} type={s.type} media={s.media} />
            ))}
            {video.captions ? <track kind="descriptions" src={video.captions} srcLang="en" label="Scene descriptions" /> : null}
          </video>
        ) : (
          scenes.map((s, i) =>
            svgs[i] ? <div key={s.src} className={`hero-scene${i === index ? " is-active" : ""}`} dangerouslySetInnerHTML={{ __html: svgs[i]! }} /> : null,
          )
        )}
      </div>
      <div className="hero-scrim" aria-hidden="true" />
      <div className="hero-grain" aria-hidden="true" />

      {children}

      <div className="hero-controls">
        <div className="container cluster" style={{ gap: "1rem" }}>
          <button type="button" className="icon-btn" onClick={toggle} aria-pressed={paused} data-enter style={{ "--i": 6 } as React.CSSProperties}>
            {paused ? (
              <svg width="16" height="16" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
                <path d="M7 4v16l13-8z" />
              </svg>
            ) : (
              <svg width="16" height="16" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
                <path d="M6 4h4v16H6zM14 4h4v16h-4z" />
              </svg>
            )}
            <span className="visually-hidden">{paused ? "Play background film" : "Pause background film"}</span>
          </button>
          {!video ? (
            <>
              <div className="scene-ticks" role="group" aria-label="Choose scene" data-enter style={{ "--i": 6 } as React.CSSProperties}>
                {scenes.map((s, i) => (
                  <button key={i} type="button" aria-current={i === index ? "true" : undefined} onClick={() => setIndex(i)}>
                    <span className="visually-hidden">
                      Scene {i + 1}: {s.caption}
                    </span>
                  </button>
                ))}
              </div>
              <p className="scene-caption" aria-live="off" data-enter style={{ "--i": 7 } as React.CSSProperties}>
                {current.caption} · Illustration
              </p>
            </>
          ) : null}
          <button
            type="button"
            className="scene-caption"
            style={{ background: "none", border: 0, cursor: "pointer", textDecoration: "underline", padding: 0 }}
            aria-expanded={showTranscript}
            aria-controls="hero-transcript"
            onClick={() => setShowTranscript((v) => !v)}
          >
            Describe film
          </button>
          <a className="scroll-cue" href="#find-your-nigeria" data-enter style={{ "--i": 8 } as React.CSSProperties}>
            Scroll to explore <span className="line" aria-hidden="true" />
          </a>
        </div>
        <div id="hero-transcript" hidden={!showTranscript} className="container">
          <div className="glass" style={{ borderRadius: "var(--r-md)", padding: "1rem", marginTop: "0.75rem", fontSize: "0.9rem" }}>
            {video ? (
              <p>{video.transcript}</p>
            ) : (
              <>
                <p>A silent sequence of original illustrations, moving from landscape to culture to city life:</p>
                <ol style={{ margin: "0.5rem 0 0", paddingLeft: "1.2rem" }}>
                  {scenes.map((s) => (
                    <li key={s.caption}>{s.alt.replace(/^Illustration: /, "")}</li>
                  ))}
                </ol>
              </>
            )}
          </div>
        </div>
      </div>
    </section>
  );
}
