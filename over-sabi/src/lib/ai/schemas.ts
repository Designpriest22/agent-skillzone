import { z } from "zod";

/** Learner-adjustable tutor settings (persisted per learning plan). */
export const tutorSettingsSchema = z.object({
  mode: z.enum(["beginner", "balanced", "immersion"]).default("beginner"),
  speed: z.number().min(0.5).max(1.5).default(1),
  correctionFrequency: z.enum(["minimal", "balanced", "thorough"]).default("balanced"),
  translationAssist: z.boolean().default(true),
  targetPercent: z.number().int().min(10).max(100).default(40),
  sessionMinutes: z
    .union([z.literal(5), z.literal(10), z.literal(15), z.literal(20), z.literal(30)])
    .default(10),
  difficulty: z.enum(["easier", "standard", "harder"]).default("standard"),
  voice: z.string().max(80).optional(),
});
export type TutorSettings = z.infer<typeof tutorSettingsSchema>;

export const DEFAULT_TUTOR_SETTINGS: TutorSettings = tutorSettingsSchema.parse({});

/** Structured tutor reply. Generated by the model under a JSON schema. */
export const tutorTurnSchema = z.object({
  reply: z
    .string()
    .describe("The tutor's spoken reply, mostly in the target language at the learner's level."),
  translation: z
    .string()
    .nullable()
    .describe(
      "Translation or gloss of the reply in the learner's explanation language, or null if translation help is off.",
    ),
  corrections: z
    .array(
      z.object({
        type: z.enum(["grammar", "vocabulary", "spelling", "tone_marks", "register", "fluency"]),
        original: z.string(),
        corrected: z.string(),
        explanation: z.string(),
      }),
    )
    .describe("Corrections to the learner's last message. Empty if nothing important to fix."),
  newVocabulary: z
    .array(z.object({ term: z.string(), meaning: z.string(), note: z.string() }))
    .describe("Up to 3 useful words or phrases the tutor just used that the learner may not know."),
  uncertainty: z
    .string()
    .nullable()
    .describe(
      "If the tutor is unsure about a translation, spelling, tone mark, idiom or cultural point, say so here. Otherwise null.",
    ),
});
export type TutorTurn = z.infer<typeof tutorTurnSchema>;

export const sessionSummarySchema = z.object({
  summary: z.string(),
  usefulExpressions: z.array(z.object({ term: z.string(), meaning: z.string() })),
  keyCorrections: z.array(z.object({ original: z.string(), corrected: z.string(), explanation: z.string() })),
  grammarInsights: z.array(z.string()),
  reviewPhrases: z.array(z.string()),
  nextStep: z.string(),
  caveats: z.string().nullable(),
});
export type SessionSummary = z.infer<typeof sessionSummarySchema>;
