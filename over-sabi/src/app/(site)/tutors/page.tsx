import type { Metadata } from "next";
import { AiBadge, TutorAvatar } from "@/components/brand/TutorAvatar";
import { ButtonLink } from "@/components/ui/Button";
import { Badge, Card, PageHeader } from "@/components/ui/primitives";
import { activeTutors } from "@/lib/content/catalog-queries";
import { listLanguages } from "@/lib/content/repo";

export const metadata: Metadata = { title: "AI tutors" };
export const revalidate = 300;

const PERSONA: Record<string, string> = {
  patient: "The patient one",
  vibe: "The easy-going one",
  precision: "The precision coach",
  culture: "The culture keeper",
  business: "The business speaker",
  heritage: "The heritage guide",
};

export default async function TutorsPage() {
  const [tutors, langs] = await Promise.all([activeTutors(), listLanguages()]);
  const langName = new Map(langs.map((l) => [l.code, l.name]));
  return (
    <div className="mx-auto max-w-6xl px-4 py-12">
      <PageHeader eyebrow="Tutors" title="Meet your AI tutors">
        Every tutor is an AI character with its own teaching style — not a real person, and never presented as
        one. Pick the style that suits you, then adjust speed, corrections, translation help and session
        length.
      </PageHeader>
      <ul className="grid gap-4 md:grid-cols-2">
        {tutors.map((t) => (
          <li key={t.id as string}>
            <Card className="flex h-full gap-5">
              <TutorAvatar avatarKey={t.avatar_key as string} name={t.name as string} size={88} />
              <div className="flex flex-col gap-2">
                <p className="flex flex-wrap items-center gap-2 font-display text-2xl font-bold">
                  {t.name as string} <AiBadge />
                </p>
                <div className="flex flex-wrap gap-1.5">
                  <Badge tone="accent">{PERSONA[t.persona as string]}</Badge>
                  <Badge>{langName.get(t.language_code as string)}</Badge>
                </div>
                <p className="font-semibold">{t.tagline as string}</p>
                <p className="text-sm text-muted">{t.bio as string}</p>
                <p className="text-sm">
                  <strong>Approach:</strong> {t.teaching_approach as string}
                </p>
                <p className="text-sm">
                  <strong>Corrections:</strong> {t.correction_style as string}
                </p>
                <p className="text-xs text-muted">Good for: {(t.specialties as string[]).join(", ")}</p>
              </div>
            </Card>
          </li>
        ))}
      </ul>
      <p className="mt-8 max-w-2xl text-sm text-muted">
        Tutor replies in Yoruba, Igbo and Hausa are generated by an AI model and are experimental: they can
        contain mistakes in tone marks, grammar or idiom. Tutors are instructed to flag uncertainty, and every
        reply has a “Report a problem” button.
      </p>
      <ButtonLink href="/start" size="lg" className="mt-6">
        Start learning
      </ButtonLink>
    </div>
  );
}
