"""Writes the shared logo data for the motion compositions (07_MOTION_IDENTITY/SOURCE_PROJECTS/dn-logo-data.js).

The compositions read the exact path data and colourways from here, so they never redraw the logo.
"""
import json
from brand import C, KIT, PATH, WORD_DESTINATION, WORD_NIGERIA, LOGO_W, LOGO_H, COLOURWAYS, LEGACY

S = KIT / "07_MOTION_IDENTITY" / "SOURCE_PROJECTS"
S.mkdir(parents=True, exist_ok=True)
data = {"paths": PATH, "word": WORD_DESTINATION, "nigeria": WORD_NIGERIA, "W": LOGO_W, "H": LOGO_H,
        "colourways": COLOURWAYS, "C": {k: v for k, v in C.items() if k not in LEGACY}, "roundel": {"cx": 93.0, "cy": 7.5, "r": 32.0}}
(S / "dn-logo-data.js").write_text("// Generated by 16_SOURCE_FILES/build/motion.py: exact logo geometry. Do not edit by hand.\nwindow.DN = "
                                   + json.dumps(data) + ";\n")
print("dn-logo-data.js", (S / "dn-logo-data.js").stat().st_size, "bytes")
