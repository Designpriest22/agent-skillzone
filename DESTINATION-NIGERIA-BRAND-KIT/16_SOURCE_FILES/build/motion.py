"""Writes the shared data file for the motion compositions (07_MOTION_IDENTITY/SOURCE_PROJECTS).

dn-logo-data.js carries the exact logo path data, colourways, the outlined campaign line and a
seamless contour tile, so the HTML compositions never redraw the logo.
"""
import json
from brand import *
from gfx import text_path
from graphics import pattern_contour

S = KIT / "07_MOTION_IDENTITY" / "SOURCE_PROJECTS"
S.mkdir(parents=True, exist_ok=True)

words = []
x = 0.0
size = 20.0
cap = size * 0.727
r = cap * 0.17
for i, wd in enumerate(["EXPERIENCE", "INVEST", "EXPLORE"]):
    d, w = text_path(wd, "Inter-SemiBold", size, 0.22, x, 0)
    x += w + size * 0.16
    words.append({"d": d, "dot": [round(x + r, 2), round(-r, 2), round(r, 2)]})
    x += 2 * r + (size * 0.62 if i < 2 else 0)

data = {
    "paths": PATH, "word": WORD_DESTINATION, "nigeria": WORD_NIGERIA, "W": LOGO_W, "H": LOGO_H,
    "colourways": COLOURWAYS, "C": C, "campaign": {"words": words, "width": round(x, 2), "cap": cap},
    "roundel": {"cx": 93.0, "cy": 7.5, "r": 32.0},
    "contourTile": pattern_contour(C["sage"], None, op=1, tile=480, seed=7),
}
(S / "dn-logo-data.js").write_text("// Generated by 16_SOURCE_FILES/build/motion.py — exact logo geometry. Do not edit by hand.\nwindow.DN = "
                                   + json.dumps(data) + ";\n")
print("dn-logo-data.js", (S / "dn-logo-data.js").stat().st_size, "bytes")
