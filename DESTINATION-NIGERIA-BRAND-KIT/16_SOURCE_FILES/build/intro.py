"""25-second brand intro: shared timeline, map data and original soundtrack.

Writes 07_MOTION_IDENTITY/SOURCE_PROJECTS/dn-intro-data.js (read by F_brand-intro-25s.html) and
08_SONIC_IDENTITY/DN_sonic-brand-intro_25s.wav/.mp3. Visual and audio events come from the same
TIMELINE, so drum strikes, word slams, map pins and the sun moment stay in sync.
"""
import json
import numpy as np
from brand import KIT
from gfx import load_geo, Proj, country_path, CITIES
import sonic as S

DUR = 25.0
EIGHTH = 2.5 / 12          # 12/8 at 96 bpm (dotted crotchet)
G0 = 4.2                   # groove starts with the Experience scene
grid = lambda n: round(G0 + n * EIGHTH, 4)

T = {
    "dur": DUR,
    "dawn": [0.0, 4.95], "headline": [1.3, 4.0],
    "iris1": [4.2, 4.95], "exp": [4.2, 10.45], "expWord": grid(3),
    "wipe2": [9.75, 10.45], "inv": [9.75, 16.05], "invWord": grid(31),
    "iris3": [15.35, 16.05], "map": [15.35, 18.3], "expoWord": grid(57), "zoom": [17.7, 18.3],
    "explore": [17.7, 21.45], "logo": [20.95, 25.0], "logoIn": [20.95, 21.45], "sun": 23.3,
    "camp": 23.85,
}
# talking-drum strikes in the Experience scene (also drive the drummer's arm)
DRUM = []
for bar in range(3):
    for k, bend in [(0, .45), (3, -.25), (5, .5), (6, .3), (9, -.3), (11, .55)]:
        t = grid(bar * 12 + k)
        if t < T["exp"][1] - .4:
            DRUM.append([t, bend])
T["drum"] = DRUM
T["pins"] = [16.55, 16.85, 17.15, 17.45]
T["birds"] = [0.7, 1.5, 2.2, 3.1]

# ---------------- map data (Natural Earth outline + city points), normalised to 1000 wide
geo = load_geo()
ng = [f for f in geo["features"] if f["properties"]["name"] == "Nigeria"][0]
pj = Proj(bbox=(2.6, 4.2, 14.75, 13.95), width=1000, pad=0)
cities = {k: [round(v, 1) for v in pj(lon, lat)] for k, (lat, lon) in CITIES.items()}
data = {"T": T, "map": {"d": country_path(ng, pj, step=2), "w": 1000, "h": round(pj.h, 1), "cities": cities,
                        "routes": [["Lagos", "Abuja"], ["Abuja", "Kano"], ["Abuja", "Calabar"], ["Lagos", "Port Harcourt"]]}}
out = KIT / "07_MOTION_IDENTITY/SOURCE_PROJECTS/dn-intro-data.js"
out.write_text("// Generated by 16_SOURCE_FILES/build/intro.py — timeline shared with the soundtrack.\nwindow.DNI = " + json.dumps(data) + ";\n")


# ---------------- soundtrack
def chirp(f0=3200, d=.12, up=1.4):
    t = S.t_(d)
    f = f0 * (1 + (up - 1) * np.sin(np.pi * t / d))
    ph = 2 * np.pi * np.cumsum(f) / S.SR
    return np.sin(ph) * np.sin(np.pi * t / d) ** 2 * .35


def whoosh(d=.7, rise=True):
    t = S.t_(d)
    n = S.rng.standard_normal(len(t))
    env = np.sin(np.pi * t / d) ** 2
    out = np.zeros_like(t)
    # sweep a band-pass by blending fixed bands (cheap and click-free)
    for i, (lo, hi) in enumerate([(300, 900), (900, 2500), (2500, 7000)]):
        w = np.clip((t / d) * 3 - i, 0, 1) if rise else np.clip(3 - (t / d) * 3 - i, 0, 1)
        out += S.bp(n, lo, hi) * w
    return out * env * .55


def soundtrack():
    m = S.Mix(DUR)
    N = S.N
    # dawn: pad swell, birds, shaker builds into the groove
    m.add(S.pad([N["D3"], N["A3"], N["E4"]], 4.8, attack=2.2, release=.8, bright=650), 0, 0, .55, .45)
    for i, t in enumerate(T["birds"]):
        for k in range(3):
            m.add(chirp(2800 + 400 * ((i + k) % 3), .09 + .03 * k), t + k * .13, .6 - .3 * (i % 3), .5, .3)
    for k, t in enumerate(np.arange(2.95, G0, EIGHTH)):
        m.add(S.shaker(vel=.2 + .5 * k / 6), t, .3, .8, .1)
    m.add(whoosh(.75), T["iris1"][0] - .5, 0, .7, .3)
    # groove: Experience → Invest → Explore (12/8, D–Bm–G–A)
    prog = [(["D3", "A3", "F#4"], "D2"), (["B3", "D4", "F#4"], "B1"), (["G3", "B3", "D4"], "G1"), (["A3", "E4", "A4"], "A1")]
    arp = [["D4", "F#4", "A4", "D5"], ["B3", "D4", "F#4", "B4"], ["G4", "B4", "D5", "G4"], ["A4", "E5", "A4", "E4"]]
    bell = [1, 0, 1, 0, 1, 1, 0, 1, 0, 1, 0, 1]
    end = T["logo"][0]
    bar = 0
    while G0 + bar * 2.5 < end - .01:
        t0 = G0 + bar * 2.5
        chord, bass = prog[bar % 4]
        section = 0 if t0 < T["inv"][0] else (1 if t0 < T["map"][0] else 2)
        m.add(S.pad([N[c] for c in chord], 2.8, attack=.4, release=.5, bright=900 + 300 * section), t0, 0, .3, .4)
        b = N[bass] * (2 if N[bass] < 60 else 1)
        m.add(S.sub(b, 1.2), t0, 0, .4, 0)
        m.add(S.sub(b, .8), t0 + 6 * EIGHTH, 0, .3, 0)
        for i in range(12):
            tt = t0 + i * EIGHTH
            if tt >= end:
                break
            m.add(S.shaker(vel=.35 if i % 3 else .6), tt, .4, .7, .08)
            if bell[i]:
                m.add(S.bell(N["E5"] * (1.5 if i % 2 else 1.25), .3, .25), tt, -.45, .33, .12)
            if i in (0, 6):
                m.add(S.low_drum(78, .8, .7), tt, 0, .65, .05)
            if section >= 1 and i in (0, 2, 3, 5, 6, 8, 9, 11):
                note = arp[bar % 4][(i // 3 + (i % 3)) % 4]
                m.add(S.thumb_piano(N[note] * (2 if section == 2 and i % 2 else 1), .9, .4), tt, .25 if i % 2 else -.15, .5, .3)
        bar += 1
    for t, bend in T["drum"]:                       # the drummer, synced to the visuals
        m.add(S.talking_drum(150 + 25 * (bend < 0), .55, bend, .9, glide=.22), t, -.2, .85, .2)
    for key in ("expWord", "invWord", "expoWord"):   # word slams
        t = T[key]
        m.add(S.low_drum(70, 1.2, 1), t, 0, .9, .15)
        m.add(S.bell(N["A5"], 1.6, .5), t, .3, .4, .5)
    m.add(whoosh(.7), T["wipe2"][0] - .1, -.3, .7, .3)
    m.add(whoosh(.7), T["iris3"][0] - .1, .3, .7, .3)
    m.add(whoosh(.6), T["zoom"][0] - .1, 0, .6, .3)
    for i, t in enumerate(T["pins"]):               # map pins pluck
        m.add(S.thumb_piano(N[["A4", "D5", "F#5", "A5"][i]], 1.2, .8), t, -.3 + .2 * i, .7, .4)
    # ending: the sonic-logo motif, sun moment on T["sun"]
    m.add(whoosh(.8, rise=False), end - .2, 0, .6, .4)
    s = T["sun"]
    m.add(S.pad([N["D3"], N["A3"]], DUR - end, attack=.6, release=1.2, bright=700), end, 0, .5, .4)
    for t, f0, bd, d in [(s - 2.1, 140, .45, .5), (s - 1.85, 172, -.25, .4), (s - 1.6, 150, .55, .9)]:
        m.add(S.talking_drum(f0, d, bd), t, -.25, .85)
    for f, dt in [("A4", -1.2), ("B4", -.95), ("D5", -.7), ("F#5", -.35)]:
        m.add(S.thumb_piano(N[f]), s + dt, .2, .7, .35)
    m.add(S.bell(N["A5"], 1.7), s, .4, .5, .5)
    m.add(S.bell(N["D6"], 1.7), s + .03, -.4, .35, .5)
    m.add(S.pad([N["D3"], N["A3"], N["E4"], N["F#4"]], DUR - s, attack=.12, release=1.4, bright=1600), s, 0, .8, .5)
    m.add(S.low_drum(70, 1.6), s, 0, .9, .15)
    m.add(S.sub(N["D2"], DUR - s), s, 0, .6, 0)
    m.add(S.talking_drum(165, .7, -.3, .5, glide=.3), s + .6, -.3, .55)
    return m.render(2.4)


if __name__ == "__main__":
    print("timeline + map written:", out.stat().st_size, "bytes")
    S.export(soundtrack(), "DN_sonic-brand-intro_25s", -16)
    print("soundtrack written")
