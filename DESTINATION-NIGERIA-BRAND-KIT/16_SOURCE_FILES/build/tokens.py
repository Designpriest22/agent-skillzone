# Adobe Swatch Exchange (.ase): RGB + CMYK swatches, grouped
def ase_block_color(name, model, vals, ctype=2):
    nm = (name + "\0").encode("utf-16-be")
    body = struct.pack(">H", len(name) + 1) + nm + model.encode() + b"".join(struct.pack(">f", v) for v in vals) + struct.pack(">H", ctype)
    return struct.pack(">HI", 0x0001, len(body)) + body


def ase_group(name, start=True):
    if not start:
        return struct.pack(">HI", 0xC002, 0)
    nm = (name + "\0").encode("utf-16-be")
    body = struct.pack(">H", len(name) + 1) + nm
    return struct.pack(">HI", 0xC001, len(body)) + body


blocks = [ase_group("Destination Nigeria RGB")]
for r in rows:
    blocks.append(ase_block_color(r["name"], "RGB ", [v / 255 for v in hex_rgb(r["hex"])], 0))
blocks.append(ase_group("", False))
blocks.append(ase_group("Destination Nigeria CMYK (coated, approx.)"))
for r in rows:
    blocks.append(ase_block_color(r["name"] + " CMYK", "CMYK", [v / 100 for v in CMYK_PRINT[r["key"]]], 0))
blocks.append(ase_group("", False))
ase = b"ASEF" + struct.pack(">HHI", 1, 0, len(blocks)) + b"".join(blocks)
(KIT / D / "DN_color_palette.ase").write_bytes(ase)

# ---------------------------------------------------------------- tokens (W3C DTCG-style JSON + CSS)
tok = {"color": {}, "font": {}, "type": {}, "space": {}, "radius": {}, "state": {}}
for r in rows:
    tok["color"][r["key"]] = {"$type": "color", "$value": r["hex"], "$description": f"{r['name']} — {r['use']}"}
for k, v in UI_STATES.items():
    tok["state"][k] = {"$type": "color", "$value": v}
for k, f in [(k, f) for k, f in FONTS.items() if k != "editorial"]:
    tok["font"][k] = {"$type": "fontFamily", "$value": [f["family"]] + [x.strip(" '") for x in f["fallback"].split(",")]}
for t, fam, wt, size, lh, tr, use in TYPE_SCALE:
    tok["type"][t] = {"$type": "typography", "$value": {"fontFamily": f"{{font.{fam}}}", "fontWeight": wt,
                      "fontSize": f"{size / 16:g}rem", "lineHeight": lh, "letterSpacing": f"{tr:g}em"},
                      "$description": use}
for i, s in enumerate(SPACE):
    tok["space"][str(i + 1)] = {"$type": "dimension", "$value": f"{s}px"}
for k, v in RADIUS.items():
    tok["radius"][k] = {"$type": "dimension", "$value": f"{v}px"}
write("12_WEBSITE_ASSETS/tokens/dn-tokens.json", json.dumps(tok, indent=2))

