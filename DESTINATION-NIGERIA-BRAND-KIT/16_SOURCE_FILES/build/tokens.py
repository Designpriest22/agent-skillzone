rows = []
for k, name, hx, group, src, use in COLORS:
    r, g, b = hex_rgb(hx)
    best_text = max([("Forest Deep", C["forest"]), ("White", "#FFFFFF")], key=lambda t: contrast(hx, t[1]))
    rows.append(dict(key=k, name=name, hex=hx, rgb=f"{r}, {g}, {b}", cmyk="/".join(map(str, CMYK_PRINT[k])),
                     group=group, source=src, use=use,
                     on_white=round(contrast(hx, "#FFFFFF"), 2), on_ivory=round(contrast(hx, C["ivory"]), 2),
                     on_forest=round(contrast(hx, C["forest"]), 2), text_on=best_text[0],
                     pantone=PANTONE_CANDIDATES.get(k, "")))

