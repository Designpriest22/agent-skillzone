"""v2 brand film (25 s): shared timeline, plate stroke data and an original soundtrack.

Story: an engraver's plate of Zuma Rock is cut stroke by stroke on a horizon line; the sun sets in
place; the plate becomes the photograph it was traced from (Experience). A second plate becomes
Agbokim Waterfalls (Invest). Four real places arrive on the beat (Explore). The logo's own drawing
resolves on the horizon, its sun lands on the final bell.

Writes 07/SOURCE_PROJECTS/dn-film-data.js (read by G_brand-film-25s.html) and
08/DN_sonic-brand-film_25s.wav/.mp3. Picture and sound read the same TIMELINE.
"""
import json
import re
import numpy as np
from PIL import Image
from brand import KIT, C, PHOTOS
import plates as PL
import sonic as S

DUR = 25.0
BAR = 2.5                  # 12/8 at 96 bpm: one bar = four dotted crotchets
BEAT = BAR / 4             # dotted crotchet = 0.625 s
EIGHTH = BAR / 12
G0 = 5.0                   # groove enters as the plate becomes a photograph

T = {
    "dur": DUR,
    "horizon": [0.25, 1.45],
    "engrave1": [0.9, 4.0], "sun1": 4.25, "cap1": [3.3, 4.1],
    "develop1": [5.0, 6.1], "expand1": [6.0, 7.2], "word1": 7.5,
    "cut2": 10.0, "engrave2": [10.05, 11.55], "develop2": [11.55, 12.35], "expand2": [12.3, 13.3], "word2": 12.5,
    "cut3": 15.0, "tiles": [15.0, 15.625, 16.25, 16.875], "word3": 17.5,
    "cut4": 20.0, "horizon4": [20.05, 20.85], "land4": [20.55, 21.9], "sun4": 22.5, "word4": [22.6, 23.5], "line4": [23.35, 24.1],
}

SP = KIT / "07_MOTION_IDENTITY/SOURCE_PROJECTS"


def plate_data(slug):
    row = [p for p in PL.PLATES if p[0] == slug][0]
    _, src, title, w, h, crop, *_ = row
    s = (KIT / "04_VECTOR_GRAPHICS_AND_ICONS/ENGRAVED_PLATES/SVG" / f"DN_plate_{slug}_forest_transparent.svg").read_text()
    eng = re.search(r'<g id="engraving">(.*?)</g>', s, re.S).group(1)
    polys = []
    for d in re.findall(r'd="([^"]+)"', eng):
        polys += ["M" + p for p in d.split("M") if p.strip()]
    sun = re.search(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"', s)
    base = slug.replace("-vignette", "").replace("-quiet", "")
    im = Image.open(KIT / "06_PHOTOGRAPHY_AND_MEDIA/LIBRARY" / f"DN_photo_{base}.jpg")
    from engrave import fit_crop
    crop = fit_crop(im.width, im.height, crop, (w, h))     # the exact region the plate was traced from
    return {"w": w, "h": h, "crop": crop, "polys": polys, "photo": f"../../06_PHOTOGRAPHY_AND_MEDIA/LIBRARY/DN_photo_{base}.jpg",
            "photoW": im.width, "photoH": im.height, "caption": PHOTOS[base]["caption"],
            "sun": [float(sun.group(i)) for i in (1, 2, 3)] if sun else None}


def write_data():
    data = {"T": T, "C": {k: C[k] for k in ("forest", "ridge", "gold", "ivory", "charcoal", "stone", "haze", "sage", "golddeep")},
            "plates": {"zuma": plate_data("zuma-rock"), "agbokim": plate_data("agbokim-waterfalls"), "zumaVignette": plate_data("zuma-rock-vignette")},
            "tiles": [{"photo": f"../../06_PHOTOGRAPHY_AND_MEDIA/LIBRARY/DN_photo_{s}.jpg", "caption": PHOTOS[s]["caption"], "focus": PHOTOS[s]["focus"]}
                      for s in ("idanre-hills", "obudu-road", "lekki-ikoyi-bridge", "bowers-tower")]}
    out = SP / "dn-film-data.js"
    out.write_text("// Generated by 16_SOURCE_FILES/build/film.py. Timeline shared with the soundtrack.\nwindow.DNF = " + json.dumps(data) + ";\n")
    return out


def burin(d=0.05, vel=1.0):
    """A short, dry scrape: band-limited noise with a fast attack. The sound of a line being cut."""
    t = S.t_(d)
    n = S.rng.standard_normal(len(t))
    env = np.clip(t / 0.004, 0, 1) * np.exp(-t / (d * 0.35))
    return S.bp(n, 2400, 7800) * env * 0.5 * vel


def soundtrack():
    m = S.Mix(DUR)
    N = S.N
    # 1 the plate: a held fifth, the burin cutting in an accelerating, quiet rhythm
    m.add(S.pad([N["D3"], N["A3"]], 5.2, attack=1.6, release=.9, bright=520), 0, 0, .5, .45)
    e0, e1 = T["engrave1"]
    k = 0
    t = e0
    while t < e1:
        m.add(burin(0.035 + 0.02 * ((k * 7) % 3) / 2, 0.35 + 0.4 * (t - e0) / (e1 - e0)), t, ((k * 37) % 9 - 4) / 6, .45, .1)
        t += 0.16 - 0.1 * (t - e0) / (e1 - e0)
        k += 1
    s1 = T["sun1"]
    for f, dt in [("A4", -.5), ("D5", -.25)]:
        m.add(S.thumb_piano(N[f], 1.4, .6), s1 + dt, .15, .6, .35)
    m.add(S.bell(N["A5"], 2.2, .55), s1, .3, .45, .5)
    # 2–4 groove: 12/8, D – Bm – G – A, entering on the photograph
    prog = [(["D3", "A3", "F#4"], "D2"), (["B3", "D4", "F#4"], "B1"), (["G3", "B3", "D4"], "G1"), (["A3", "E4", "A4"], "A1")]
    arp = [["D4", "F#4", "A4", "D5"], ["B3", "D4", "F#4", "B4"], ["G4", "B4", "D5", "G4"], ["A4", "E5", "A4", "E4"]]
    end = T["cut4"]
    for bar in range(int((end - G0) / BAR)):
        t0 = G0 + bar * BAR
        chord, bass = prog[bar % 4]
        sec = 0 if t0 < T["cut2"] else (1 if t0 < T["cut3"] else 2)
        m.add(S.pad([N[c] for c in chord], 2.8, attack=.5, release=.6, bright=800 + 250 * sec), t0, 0, .32, .4)
        b = N[bass] * (2 if N[bass] < 60 else 1)
        m.add(S.sub(b, 1.2), t0, 0, .42, 0)
        m.add(S.sub(b, .8), t0 + 6 * EIGHTH, 0, .3, 0)
        for i in range(12):
            tt = t0 + i * EIGHTH
            m.add(S.shaker(vel=.3 if i % 3 else .55), tt, .4, .6, .06)
            if i in (0, 6):
                m.add(S.low_drum(78, .8, .7), tt, 0, .62, .05)
            if sec >= 1 and i in (0, 3, 5, 6, 9, 11):
                note = arp[bar % 4][(i // 3 + i % 2) % 4]
                m.add(S.thumb_piano(N[note] * (2 if sec == 2 and i % 2 else 1), .9, .38), tt, .25 if i % 2 else -.15, .48, .3)
        if sec == 0:   # talking drum answers in the Experience bars
            for kk, bend in [(0, .4), (3, -.25), (5, .45), (9, -.3), (11, .5)]:
                m.add(S.talking_drum(150 + 22 * (bend < 0), .5, bend, .8, glide=.2), t0 + kk * EIGHTH, -.2, .7, .2)
    for key in ("word1", "word2", "word3"):          # each word lands on a low drum and a bell
        t = T[key]
        m.add(S.low_drum(70, 1.2, 1), t, 0, .85, .15)
        m.add(S.bell(N["A5"], 1.6, .45), t, .3, .38, .5)
    for t in (T["cut2"], T["cut3"]):                  # hard cuts land on the downbeat
        m.add(S.low_drum(66, 1.0, .9), t, 0, .8, .1)
    for i, t in enumerate(T["tiles"]):                # the four places pluck in
        m.add(S.thumb_piano(N[["A4", "D5", "F#5", "A5"][i]], 1.2, .8), t, -.3 + .2 * i, .68, .4)
    e0, e1 = T["engrave2"]
    t = e0
    while t < e1:
        m.add(burin(0.03, .45), t, ((int(t * 100) * 37) % 9 - 4) / 6, .35, .1)
        t += 0.09
    # 5 the logo: groove stops; the sonic-logo motif; the sun lands on the bell
    s = T["sun4"]
    m.add(S.pad([N["D3"], N["A3"]], DUR - end, attack=.5, release=1.2, bright=650), end, 0, .5, .4)
    m.add(S.low_drum(66, 1.4, .9), end, 0, .8, .15)
    for t, f0, bd, d in [(s - 2.1, 140, .45, .5), (s - 1.85, 172, -.25, .4), (s - 1.6, 150, .55, .9)]:
        m.add(S.talking_drum(f0, d, bd), t, -.25, .85)
    for f, dt in [("A4", -1.2), ("B4", -.95), ("D5", -.7), ("F#5", -.35)]:
        m.add(S.thumb_piano(N[f]), s + dt, .2, .7, .35)
    m.add(S.bell(N["A5"], 1.7), s, .4, .5, .5)
    m.add(S.bell(N["D6"], 1.7), s + .03, -.4, .35, .5)
    m.add(S.pad([N["D3"], N["A3"], N["E4"], N["F#4"]], DUR - s, attack=.12, release=1.4, bright=1500), s, 0, .75, .5)
    m.add(S.low_drum(70, 1.6), s, 0, .9, .15)
    m.add(S.sub(N["D2"], DUR - s), s, 0, .6, 0)
    return m.render(2.0)


if __name__ == "__main__":
    import sys
    out = write_data()
    if "--data-only" in sys.argv:
        raise SystemExit
    print("film data:", round(out.stat().st_size / 1e6, 2), "MB")
    S.export(soundtrack(), "DN_sonic-brand-film_25s", -16)
    print("soundtrack written")
